func productionPlanFieldDescription(key, kind string, section productionDocumentSection) string {
	return productionPlanFieldDescriptionForSchema(key, kind, section, 1)
}

func productionPlanFieldDescriptionForSchema(key, kind string, section productionDocumentSection, schemaVersion int) string {
	return productionPlanFieldContentDescription(key, kind, section, schemaVersion) + " 字段只填正文，系统自动生成章节标题；不得包含一级或二级 Markdown 标题，细分使用三级或更低标题，代码围栏必须闭合。"
}

func productionPlanFieldContentDescription(key, kind string, section productionDocumentSection, schemaVersion int) string {
	if requirement := productionAssetFieldRequirements[kind][section.Key]; requirement != "" {
		return section.Title + "。" + requirement
	}
	if requirement := productionPlanFieldRequirements[key][section.Key]; requirement != "" {
		description := section.Title + "。" + requirement + productionPlanExecutionRequirements[key][section.Key]
		if key == "story" && section.Key == "episodeArchitecture" {
			description += productionEpisodeArchitectureContract()
		}
		if key == "story" && section.Key == "relationships" {
			description += productionRelationshipLedgerContract()
		}
		return description
	}
	switch section.Key {
	case "facts":
		return section.Title + "。区分项目已定信息、计划与创作设计；不得把其他项目或尚不存在的正文写成事实依据。"
	case "prompt":
		return section.Title + "。给可直接复用的具体模板，引用已注册资产编码；只覆盖本稿职责，不重复全剧上下文。用槽位、字段引用和一条简短组合示例表达；不得把本稿其他章节、全部资产设计再次抄入 prompt。公共规范只能引用已注册基础码，未分配的造型用基础码+状态名描述，不自行添加 -V01 等变体后缀。"
	case "negativePrompt":
		return section.Title + "。逐条说明会破坏本项目身份、风格、世界规则或连续性的具体禁止变化，不用笼统的高质量替代。"
	case "continuity":
		return section.Title + "。明确不变项、允许变化的触发条件及核对方法；沿用本版公共规范。"
	case "uncertainties":
		return section.Title + "。明确设计假设与真正缺少依据的事项及影响；不把必需制作设计统一留待确认，不适用时说明理由。"
	}
	return section.Title + "。写本项目可执行的具体设计，遵循已完成前置规范；不能只复述标题或写待补充。"
}

